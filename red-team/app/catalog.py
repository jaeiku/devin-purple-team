"""Pre-authored, deterministic synthetic vulnerability catalog (Telco focus).

Every entry here is hand-written and static -- nothing in this catalog is
generated by an LLM. Each entry adds ONE self-contained synthetic file to the
Superset fork under ``telco_security/``; no real Superset internals are ever
edited. The files model realistic telco/OSS-BSS workloads (subscriber PII, CDR
ingestion, ClickHouse analytics, billing, network-element integration) so the
blue team has a realistic remediation target.

The catalog is the contract between red and blue: ``remediation`` is what the
GitHub issue tells Devin to do, and ``category``/``severity`` drive the labels
and the dashboard breakdown.
"""

