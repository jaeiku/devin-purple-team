def issue_body(
    vuln: Vulnerability, repo: str, commit_url: str, branch: str
) -> str:
    """Render the GitHub issue body the blue team / Devin will act on."""

    lines = [
        f"## {vuln.title}",
        "",
        f"**Severity:** `{vuln.severity}` | **Category:** "
        f"`{vuln.category}` | **CWE:** `{vuln.cwe}`",
        f"**Repository:** `{repo}`",
        f"**Vulnerable file:** `{vuln.file_path}`",
        f"**Injected on branch:** `{branch}`",
        "",
        "### Description",
        vuln.description,
        "",
        "### Where it lives",
        f"The vulnerable code was added as a self-contained synthetic file at "
        f"`{vuln.file_path}` on branch `{branch}`. No upstream Superset "
        f"code was modified. Any fix pull request must target branch `{branch}` "
        "rather than the default branch.",
    ]
    if commit_url:
        lines += ["", f"Injection commit: {commit_url}"]
    lines += [
        "",
        "### Remediation guidance",
        vuln.remediation,
        "",
        "### Acceptance criteria",
        f"- [ ] `{vuln.file_path}` no longer contains the vulnerable pattern "
        f"({vuln.detection_hint or vuln.category}).",
        "- [ ] The module keeps its public function signatures so callers do "
        "not break.",
        "- [ ] A pull request is opened that closes this issue.",
        "",
        "---",
        "_Synthetic vulnerability injected by the purple-team red service for "
        "autonomous-remediation validation. Not a real production finding._",
    ]
    return "\n".join(lines)
