@dataclass(frozen=True)
class Vulnerability:
    """A single deterministic catalog entry."""

    vuln_id: str
    title: str
    description: str
    severity: str
    category: str
    cwe: str
    file_path: str
    content: str
    remediation: str
    detection_hint: str = ""
    tags: list[str] = field(default_factory=list)

    def as_dict(self) -> dict[str, Any]:
        return {
            "vuln_id": self.vuln_id,
            "title": self.title,
            "description": self.description,
            "severity": self.severity,
            "category": self.category,
            "cwe": self.cwe,
            "file_path": self.file_path,
            "branch_pattern": f"red-team/{self.vuln_id}/run-<n>",
            "content": self.content,
            "remediation": self.remediation,
            "detection_hint": self.detection_hint,
            "tags": self.tags,
        }

    def branch_for(self, instance: int) -> str:
        """Return the branch name for a numbered injection instance."""

        return f"red-team/{self.vuln_id}/run-{instance}"


